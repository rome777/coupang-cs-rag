export function buildCustomerSystemPrompt(scenario?: Partial<Scenario>): string {
  if (!scenario) return BASE_CUSTOMER_SYSTEM_MESSAGE;

  let context = `\n\n[당신의 고객 정보 및 현재 상황 - 주문번호는 상담원이 직접 묻기 전까지 먼저 말하지 마세요!]`;
  if (scenario.customerName) context += `\n- 당신의 성함: ${scenario.customerName}`;
  if (scenario.isWowMember !== undefined) context += `\n- 와우회원 여부: ${scenario.isWowMember ? "로켓와우 회원 (유료 구독 중이라 자부심 있음)" : "일반 회원"}`;
  if (scenario.productName) context += `\n- 문제의 주문 상품: ${scenario.productName}`;
  if (scenario.situationSummary) context += `\n- 현재 겪고 있는 피해 상황: ${scenario.situationSummary}`;
  if (scenario.orderNumber) context += `\n- (비공개 메모: 상담원이 명시적으로 주문번호를 물어볼 때만 알려줄 것 -> ${scenario.orderNumber})`;

  context += `\n\n위 상황에 100% 몰입하여, 절대 주문번호를 먼저 떠벌리지 말고, 모바일 1:1 채팅으로 화난 한국인 고객답게 상담원(user)에게 따지세요!`;

  return `${BASE_CUSTOMER_SYSTEM_MESSAGE}${context}`;
}
